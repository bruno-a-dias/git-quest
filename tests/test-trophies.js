const {MISSIONS}=require('../js/missions.js');
const T=require('../js/trophies.js');
let fails=0;const bad=m=>{fails++;console.log('ERRO: '+m);};
const ids=T.TROPHIES.map(t=>t.id);
if(new Set(ids).size!==ids.length)bad('ids repetidos');
const cn=T.counts([]);
if(cn.bronze.total!==5||cn.silver.total!==4||cn.gold.total!==4||cn.platinum.total!==1)bad('distribuição por nível '+JSON.stringify(cn));
if(T.earned({done:{}},MISSIONS).length)bad('save vazio não deve ter troféus');
const S={done:{0:{xp:100}}};
if(T.earned(S,MISSIONS).join()!=='b_first')bad('primeira missão '+T.earned(S,MISSIONS));
const full={done:{},qf:2,bestCombo:5,exp:1,chw:3,perfect:10};
MISSIONS.forEach((m,i)=>{full.done[i]={xp:50};});
const all=T.earned(full,MISSIONS);
if(all.length!==T.TROPHIES.length||!all.includes('p_all'))bad('tudo feito deveria dar todos, incluindo a platina: '+all.length);
const noExp=Object.assign({},full,{exp:0});
if(T.earned(noExp,MISSIONS).includes('p_all'))bad('platina exige todos os outros troféus');
const w1={done:{}};MISSIONS.forEach((m,i)=>{if(m.w===0)w1.done[i]={xp:50};});
if(!T.earned(w1,MISSIONS).includes('b_w1'))bad('mundo 1');
console.log(fails?('\n'+fails+' problemas'):'TROFÉUS OK ('+T.TROPHIES.length+')');
process.exit(fails?1:0);
